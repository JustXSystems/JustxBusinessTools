-- Recurring invoice profiles (Zoho / QuickBooks parity). Child invoices reuse ims_invoices.

CREATE TABLE IF NOT EXISTS ims_recurring_invoices (
  id CHAR(36) NOT NULL,
  tenant_id INT UNSIGNED NOT NULL,
  profile_name VARCHAR(160) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'active',
  frequency VARCHAR(12) NOT NULL DEFAULT 'months',
  repeat_every SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  start_on DATE NOT NULL,
  next_run_on DATE NOT NULL,
  end_on DATE NULL,
  auto_issue TINYINT(1) NOT NULL DEFAULT 0,
  customer_id CHAR(36) NULL,
  customer_name VARCHAR(200) NOT NULL,
  customer_gstin VARCHAR(20) NULL,
  customer_address VARCHAR(500) NULL,
  customer_mobile VARCHAR(40) NULL,
  place_of_supply VARCHAR(80) NULL,
  intra_state TINYINT(1) NOT NULL DEFAULT 1,
  customer_po_no VARCHAR(64) NULL,
  ship_to_name VARCHAR(200) NULL,
  ship_to_gstin VARCHAR(20) NULL,
  ship_to_address VARCHAR(500) NULL,
  ship_to_state VARCHAR(80) NULL,
  ship_to_mobile VARCHAR(40) NULL,
  `lines` JSON NOT NULL,
  shipping_charges DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  shipping_gst_rate DECIMAL(5, 2) NOT NULL DEFAULT 0.00,
  round_to_rupee TINYINT(1) NOT NULL DEFAULT 1,
  payment_terms_days SMALLINT UNSIGNED NULL,
  account_manager_id INT UNSIGNED NULL,
  account_manager_name VARCHAR(120) NULL,
  notes TEXT NULL,
  terms TEXT NULL,
  last_run_on DATE NULL,
  last_invoice_id CHAR(36) NULL,
  last_invoice_no VARCHAR(48) NULL,
  run_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_by INT UNSIGNED NULL,
  created_by_name VARCHAR(120) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_ims_recur_due (tenant_id, status, next_run_on),
  KEY idx_ims_recur_customer (tenant_id, customer_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE ims_invoices
  ADD COLUMN recurring_id CHAR(36) NULL AFTER source_ref,
  ADD COLUMN retention_pct DECIMAL(5, 2) NOT NULL DEFAULT 0.00 AFTER shipping_tax,
  ADD COLUMN retention_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00 AFTER retention_pct,
  ADD KEY idx_ims_invoice_recur (tenant_id, recurring_id);
